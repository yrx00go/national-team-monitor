def norm_title(t):
    """去掉东财搜索塞进标题的高亮标签。"""
    return re.sub(r'</?em>', '', t or '').strip()


def _org_of(title):
    """这条标题真正代表的是哪一家的观点。

    ⚠⚠ 这一层是整个模块最重要的修正（2026-11-14 实测发现）。
    最初我用搜索结果的 `src`（媒体名）当聚合键，结果是这样：

        · 申万宏源 2027 年会 → 「静待第二阶段上涨」
        · 21世纪经济报道《申万宏源定调A股：明年春季行情可期》   → 1 票
        · 财联社《申万宏源傅静涛：A股仍处两段论》              → 1 票
        · 央广财经《申万宏源2027投资年在上海举行 研判将迎…》    → 1 票
        · 上海证券报《…静待"第二阶段上涨"》                    → 1 票

      **同一个观点被计了 4 票**，看起来像「4 家机构一致看多」，
      实际是「1 家机构说了 1 次，4 家媒体转述」。

      这不是小数点问题，是把「转载量」冒充「共识度」。
      媒体发稿勤不勤，和市场怎么看，是两件事。

    所以聚合键必须是**被点名的机构**，而不是**发稿的媒体**。
    标题里点不出机构名的（「十大券商看后市」「关于A股后市 机构最新研判」），
    按「汇集稿」单独一票 —— 它确实代表一批机构的综合态度，
    但它的权重不能和「一家机构的明确表态」相同，页面要标出来。
    """
    t = norm_title(title)
    for org in NAMED_ORG:
        if org in t:
            return org, 'named'
    return '汇集稿（未点名机构）', 'digest'


