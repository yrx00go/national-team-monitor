def _norm(t):
    return re.sub(r'</?em>', '', t or '').strip()


def is_official(src):
    """这条稿子的发布方是不是官方一手。"""
    s = (src or '').strip()
    if not s:
        return False
    # ⚠ 必须排除财经资讯产品。它们名字里带「新华」，但不是官方发布。
    if s in ('新华财经', '人民财讯', '人民网财经'):
        return False
    return any(s.startswith(o) or s == o for o in OFFICIAL)


