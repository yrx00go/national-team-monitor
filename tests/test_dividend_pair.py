#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""股息率年化配对的过渡期（离线，不联网）。

对应 2026-11-27 修的那个 bug：一家公司第一次改成年内两次派息时，
「最新中期 + 上一财年年度」会把上一财年那一整年的钱也算进去，
股息率凭空虚高。招行 600036 因此有 114 个交易日显示 7.8~8.4%（真实约 5.2%）。

⚠ 为什么值得单独写测试：
   这个错**不报错、不崩、不缺席**，只是数字偏大一截，而且只在一种年份里出现
   （改派息节奏的那一年）。也就是说：正常年份跑一万次都对，出问题那次
   看起来也一样正常。下次再有人动这段配对逻辑，靠肉眼看不出区别。

跑法：python3 tests/test_dividend_pair.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'scripts'))

import fetch_dividend as m

ok_n = fail_n = 0


def chk(label, got, want):
    global ok_n, fail_n
    if got == want:
        ok_n += 1
        print(f'  ✅ {label}: {got!r}')
    else:
        fail_n += 1
        print(f'  ❌ {label}: 得到 {got!r}，应为 {want!r}')


def rec(ex, dps, period):
    return {'ex': ex, 'dps': dps, 'period': period}


# ────────────────────────────────────────────────────────────────
print('## 招行 600036：2025 年首次改中期派息（真数据，来自东财 RPT_SHAREBONUS_DET）')
#
#   2024-12-31  每 10 股 20.00 → 2.000 元/股   全年一次（不是尾款）
#   2025-06-30  每 10 股 10.13 → 1.013 元/股   第一次中期
#   2025-12-31  每 10 股 10.03 → 1.003 元/股   当年尾款
CMB = [
    rec('2023-07-13', 1.972, '2022-12-31'),
    rec('2024-07-11', 1.972, '2023-12-31'),
    rec('2025-07-11', 2.000, '2024-12-31'),
    rec('2026-01-16', 1.013, '2025-06-30'),
    rec('2026-07-10', 1.003, '2025-12-31'),
]

# 2026-01-16 之前：只有年度 → 年化就是那一年
chk('2026-01-15（只有年度）', m.annual_dps(CMB[:3])[0], 2.0)

# 2026-01-16 ~ 07-09：最新是 2025 中期，上一财年 FY2024 只有年度一笔
#   ⚠ 旧逻辑在这算 1.013 + 2.000 = 3.013（→ 7.78%），虚高 50%
dps, pair = m.annual_dps(CMB[:4])
chk('2026-01-16（过渡期，不得叠加）', dps, 2.0)
chk('  └ 配对只用上一财年年度', pair, '2024-12-31')

# 2026-07-10 之后：2025 年度尾款到了 → 本财年中期 + 尾款
chk('2026-07-10（尾款到了）', m.annual_dps(CMB)[0], 2.016)

# 按价格算一遍：错的那个版本会是什么样，留在断言里当反面样本
chk('  过渡期 5.17%（不是 7.78%）', round(2.0 / 38.72 * 100, 2), 5.17)
chk('  bug 版本 7.78%', round(3.013 / 38.72 * 100, 2), 7.78)


# ────────────────────────────────────────────────────────────────
print('\n## 银行常态（中期 + 年度）：原口径必须原样保留')
#
#   工行 601398 实测：2025-12-31 派 0.1689（尾款）、2026-06-30 派 0.1511（中期）
#   站在 2026 中期已除权的时点，未来 12 个月拿到的是 2026 中期 + 2025 年度尾款
ICBC = [
    rec('2025-07-10', 0.1646, '2024-12-31'),
    rec('2025-11-20', 0.1414, '2025-06-30'),
    rec('2026-07-09', 0.1689, '2025-12-31'),
    rec('2026-11-20', 0.1511, '2026-06-30'),
]
dps, pair = m.annual_dps(ICBC)
chk('工行 最新中期 + 上年尾款', dps, 0.32)
chk('  └ 配对是 2025-12-31 + 2026-06-30', pair, '2025-12-31 + 2026-06-30')

# 上一财年有中期 → 判据必须走「叠加」那一支，不能被新规则误伤
chk('  判据：上年有中期才叠加', len([r for r in ICBC if r['period'].startswith('2025') and r['period'][5:7] != '12']) > 0, True)


# ────────────────────────────────────────────────────────────────
print('\n## 纯年度派息的公司：不能因为「没有中期」就算成 0')
ANNUAL_ONLY = [
    rec('2025-06-20', 0.35, '2024-12-31'),
    rec('2026-06-18', 0.38, '2025-12-31'),
]
chk('年度单笔', m.annual_dps(ANNUAL_ONLY)[0], 0.38)


# ────────────────────────────────────────────────────────────────
print('\n## 季度派息：同一财年的中期必须全算（原来只取最近一期，会漏）')
QUARTERLY = [
    rec('2025-05-10', 0.10, '2025-03-31'),
    rec('2025-08-10', 0.10, '2025-06-30'),
    rec('2025-11-10', 0.10, '2025-09-30'),
    rec('2026-03-10', 0.12, '2025-12-31'),
]
chk('四期合计', m.annual_dps(QUARTERLY)[0], 0.42)


# ────────────────────────────────────────────────────────────────
print('\n## 边界：没有任何记录 / 只有一期')
chk('空记录', m.annual_dps([])[0], 0.0)
chk('只有一期中期（无上年可比）', m.annual_dps([rec('2026-06-30', 0.2, '2026-06-30')])[0], 0.2)


# ────────────────────────────────────────────────────────────────
print('\n## 回归：时间戳必须走北京时钟')
#
#   ⚠ 2026-11-27：CI runner 是 UTC，脚本里写 datetime.now() 会把北京 15:59
#     记成 07:59，页头「生成于」长期早 8 小时。
src = open(os.path.join(os.path.dirname(HERE), 'scripts', 'fetch_dividend.py'),
           encoding='utf-8').read()
chk('★ updated_at 用 _td.bj_stamp()', "'updated_at': _td.bj_stamp()" in src, True)
chk('★★ 没有 datetime.now() 的残留（注释除外）',
    'datetime.now()' in src.split('"""', 2)[-1].replace('datetime.now()`', ''), False)

print(f'\n{"=" * 50}\n通过 {ok_n} 项，失败 {fail_n} 项')
sys.exit(0 if fail_n == 0 else 1)
