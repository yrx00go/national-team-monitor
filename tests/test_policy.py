def chk(name, got, want):
    global _n
    _n += 1
    ok = (got == want) if not callable(want) else want(got)
    print(f'{"  ok " if ok else "  !! "}{name}')
    if not ok:
        print(f'        实际 {got!r}　期望 {want!r}')
        _fail.append(name)


def section(t):
    print(f'\n=== {t} ===')


