section('7. 口径必须写出「不能怎么读」')

_cv = P.caveats(_pol)
_cv_txt = ' '.join(_cv)

chk('★★★ 必须点明「官方稿是发布，不是解读」',
    '发布' in _cv_txt and '不是解读' in _cv_txt, True)
chk('★★★ 必须声明这一层「不判方向」', '不判方向' in _cv_txt, True)
chk('★★★ 必须写窗口起止，不能只给一个数',
    ('2026-11-08' in _cv_txt) and ('2026-11-14' in _cv_txt), True)
chk('★★ 必须解释「某天 0 条是正常的」（政策有节奏）',
    '0 条' in _cv_txt or '零条' in _cv_txt, True)
chk('★★ 必须写出官媒里政策稿占比很低这个事实',
    '112' in _cv_txt and '27' in _cv_txt, True)
chk('★★ 必须区分「一手发布」和「财经媒体转述」',
    '转述' in _cv_txt or '二手' in _cv_txt, True)
chk('★ 至少要 4 条口径', len(_cv) >= 4, True)

# 口径里不许**断言**方向。
# ⚠ 但不能一刀切查词 ——「不是「所以会涨」」正是这句话的正确写法，
#   它是在否定涨跌，不是在断言涨跌。原断言把它误判成违规了。
#   所以先把「不是「…」」和「不…涨/跌」这类否定式剥掉，再查剩下的。
_cv_pos = re.sub(r'不是[「『][^」』]*[」』]', '', _cv_txt)
_cv_pos = re.sub(r'不[判会看](涨|跌)', '', _cv_pos)
chk('★★★ 口径文案里不许断言涨跌（否定式不算）',
    any(w in _cv_pos for w in ['会涨', '会跌', '利好', '利空',
                               '看涨', '看跌', '偏多', '偏空']), False)


